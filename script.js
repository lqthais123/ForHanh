// ================================
// RECORD PAGE
// ================================

const params = new URLSearchParams(window.location.search);
const token = params.get("token");

const record = records[token];

if (record) {

    const numberElement =
        document.getElementById("record-number");

    const titleElement =
        document.getElementById("record-title");

    const audioPlayer =
        document.getElementById("audio-player");


    if (numberElement) {
        numberElement.textContent = record.number;
    }


    if (titleElement) {
        titleElement.textContent = record.title;
    }


    if (audioPlayer) {
        audioPlayer.src = record.audio;
    }


    // Special note for Hug
    if (record.number === "06") {

        const noteElement =
            document.querySelector(".record-note");

        if (noteElement) {
            noteElement.textContent =
                "when you need a hug";
        }
    }

} else {

    const numberElement =
        document.getElementById("record-number");

    const titleElement =
        document.getElementById("record-title");


    if (numberElement) {
        numberElement.textContent = "—";
    }


    if (titleElement) {
        titleElement.textContent = "—";
    }
}


