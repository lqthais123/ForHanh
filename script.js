/* =========================
   READ TOKEN
========================= */

const params = new URLSearchParams(window.location.search);

const token = params.get("t");

const record = records[token];


/* =========================
   LOAD RECORD
========================= */

if (record) {

    const numberElement =
        document.getElementById("record-number");

    const titleElement =
        document.getElementById("record-title");

    const audioPlayer =
        document.getElementById("audio-player");


    if (numberElement) {
        numberElement.textContent = record.number;
    }


    if (titleElement) {
        titleElement.textContent = record.title;
    }


    if (audioPlayer) {

        audioPlayer.src = record.audio;

        audioPlayer.load();

    }


    document.title =
        `${record.title} — For Hanh`;

}


/* =========================
   INVALID TOKEN
========================= */

else {

    const numberElement =
        document.getElementById("record-number");

    const titleElement =
        document.getElementById("record-title");

    const audioPlayer =
        document.getElementById("audio-player");


    if (numberElement) {
        numberElement.textContent = "";
    }


    if (titleElement) {
        titleElement.textContent = "Nothing here.";
    }


    if (audioPlayer) {
        audioPlayer.remove();
    }


    document.title = "For Hanh";

}